# Lines the downloadable template writes for the teacher's benefit. They are
# not exam content, and without this the footer is swallowed into the last
# question's text and printed on the exam paper.
BOILERPLATE_PATTERNS = [
    re.compile(r"generated by\s+nuventa", re.IGNORECASE),
    re.compile(r"upload at:\s*dashboard", re.IGNORECASE),
    re.compile(r"supported formats:", re.IGNORECASE),
    re.compile(r"^#", re.IGNORECASE),
    re.compile(r"delete (the )?example rows", re.IGNORECASE),
]


def is_template_boilerplate(text: str) -> bool:
    """True when a line is template guidance rather than exam content."""
    stripped = (text or "").strip()
    if not stripped:
        return False
    return any(p.search(stripped) for p in BOILERPLATE_PATTERNS)


# --- Pasted-text parsing (no file, teacher pastes raw exam text) ----------
#
# Matches a section header such as "Section A", "SECTION A:", "Section A -
# Objective Questions (15 Marks)". Used both to find real section starts and
# to spot table-of-contents-style listings ("Section A: Objective (15
# Questions)" followed immediately by "Section B: Theory (5 Questions)") so
# those don't get mistaken for a section with no questions in it.
SECTION_HEADER_RE = re.compile(
    # "Section A", "Section A: Objective", "SECTION B - Theory", and with
    # just a space, "SECTION B LITERARY APPRECIATION - Choose the best option".
    # Papers also number their sections - "SECTION 2", "Section II", "PART B",
    # "Part Two" - and those were read as questions, so a theory section
    # headed that way was folded into the last objective question.
    r'^(?:section|part)\s+([a-z]|\d{1,2}|[ivx]{1,4}|one|two|three|four|five)\b'
    r'(?:(?:\s*[:\-–—.]\s*|\s+)(.*))?$',
    re.IGNORECASE
)

# A heading that names the kind of section with no "Section B" in front:
# "THEORY", "Theory Questions (40 marks)", "OBJECTIVE TEST", "ESSAY".
KIND_HEADING_RE = re.compile(
    r'^(?:the\s+)?(objectives?|multiple[\s-]*choice|theory|essay|subjective|practicals?)'
    r'(?:\s+(?:questions?|section|test|part|paper))?\s*[:.\-–—]?\s*(?:\(.*\))?\s*[:.]?$',
    re.IGNORECASE
)

# Longer than this, a line starting "Section 3 of..." is a question, not a heading.
HEADING_MAX_CHARS = 100


def section_heading(line: str) -> Optional[Tuple[str, str]]:
    """
    (name, subtitle) when the line heads a section, else None. The subtitle
    is what says which kind of section it is: "Theory" in "Section B: Theory".
    """
    text = line.strip()
    if len(text) > HEADING_MAX_CHARS or text.endswith('?'):
        return None
    m = SECTION_HEADER_RE.match(text)
    if m:
        label = m.group(1)
        label = label.upper() if len(label) <= 4 else label.capitalize()
        subtitle = (m.group(2) or '').strip()
        word = 'Part' if text.lower().startswith('part') else 'Section'
        return (f'{word} {label}: {subtitle}' if subtitle else f'{word} {label}'), subtitle
    if KIND_HEADING_RE.match(text):
        return text, text
    return None

# A multiple-choice option line: "A. text", "B) text", "C: text", "(D) text"
# - upper or lower case letter, A through E.
OPTION_LINE_RE = re.compile(r'^\(?([A-Ea-e])[\.\):]\s*(.+)$')

OPTION_LETTERS = 'abcde'

# A line this long is a paragraph of a passage, not a heading or an
# instruction such as "Read the passage carefully and answer the questions".
PASSAGE_LINE_CHARS = 120


def split_passage(lines: List[str]) -> Tuple[List[str], List[str]]:
    """
    (instructions, passage) from the lines above a section's first question.

    The passage starts at its first paragraph; the short lines before it,
    "COMPREHENSION" and "Read the passage carefully...", are the section's
    instructions. Lines with no paragraph among them are all instructions.
    """
    lines = [line for line in lines if line and line.strip()]
    for i, line in enumerate(lines):
        if len(line.strip()) >= PASSAGE_LINE_CHARS:
            return lines[:i], lines[i:]
    return lines, []


def split_inline_options(line: str) -> List[str]:
    """
    One option per line, from a line typed with several on it.

    Papers are often set with the options run together, "A. keep B. put
    C. make D. let" or "(a) Girls alone (b) Boys alone", and the readers
    below want each option on its own line. Only a line that starts with an
    option is split, and only at the next letters in order (B after A, then
    C...) written the same way, so a question that merely mentions "B." is
    left alone.
    """
    first = OPTION_LINE_RE.match(line)
    if not first:
        return [line]

    letter = first.group(1)
    upper = letter.isupper()
    bracketed = line.startswith('(')
    position = OPTION_LETTERS.index(letter.lower())

    starts = [0]
    cursor = first.end(1) + 1
    for nxt in OPTION_LETTERS[position + 1:]:
        mark = nxt.upper() if upper else nxt
        # "(b)" needs no space after it ("(b)for"); "B." must stand alone.
        pattern = (r'\(' + mark + r'\)' if bracketed
                   else r'(?<=\s)' + mark + r'[\.\)]\s')
        found = re.compile(pattern).search(line, cursor)
        if not found:
            break
        starts.append(found.start())
        cursor = found.end()

    if len(starts) == 1:
        return [line]
    starts.append(len(line))
    return [line[a:b].strip() for a, b in zip(starts, starts[1:]) if line[a:b].strip()]


# Where a question's options start when they are typed on the question's own
# line: "40. What is 2 + 2? A. 3 B. 4 C. 5 D. 6", or "... (a) 3 (b) 4".
INLINE_OPTION_START_RE = re.compile(r'(?<=[\s?:.])(?:\([Aa]\)|[Aa][\.\)])(?=\s*\S)')

# The next question typed onto the end of an option: "D. Kano 40. What is...".
RUN_IN_QUESTION_RE = re.compile(r'^(.*?\S)\s+(\d{1,3})[\.\)]\s+(\S.*)$')


def options_restart(prev: str, letter: str) -> bool:
    """Whether an option lettered A after B, C or D starts a new question's options."""
    return letter.lower() == 'a' and prev.lower() != 'a'


def _option_letter(line: str) -> Optional[str]:
    m = OPTION_LINE_RE.match(line)
    return m.group(1) if m else None


def mend_objective_lines(lines: List[str]) -> List[str]:
    """
    Lines of an objective section put back into one line per question and
    one per option, where the teacher typed them otherwise:

    - a question with its options on its own line, "What is 2 + 2? A. 3 B. 4",
      or with only "A." there and the rest below;
    - the next question run onto the end of an option, "D. Kano 40. What is
      the capital?", with its options under it;
    - an option typed without its letter, between B. and D.

    Each of these merged two questions into one, or took one apart, so a
    question went missing from the converted exam.
    """
    split: List[str] = []
    for n, line in enumerate(lines):
        if OPTION_LINE_RE.match(line):
            split.append(line)
            continue
        m = INLINE_OPTION_START_RE.search(line)
        stem = line[:m.start()].strip() if m else ''
        if m and stem:
            parts = split_inline_options(line[m.start():])
            nxt = lines[n + 1] if n + 1 < len(lines) else ''
            if len(parts) >= 2 or (_option_letter(nxt) or '').lower() == 'b':
                split.extend([stem, *parts])
                continue
        split.append(line)

    out: List[str] = []
    for n, line in enumerate(split):
        letter = _option_letter(line)
        prev = _option_letter(out[-1]) if out else None
        if letter and prev and options_restart(prev, letter):
            # The options start again at A: a new question, whose stem may
            # have been typed onto the end of the option before.
            run_in = RUN_IN_QUESTION_RE.match(out[-1])
            if run_in and OPTION_LINE_RE.match(run_in.group(1)):
                out[-1] = run_in.group(1)
                out.append(f'{run_in.group(2)}. {run_in.group(3)}')
        elif not letter and prev and not NUMBERED_LINE_RE.match(line):
            nxt = _option_letter(split[n + 1]) if n + 1 < len(split) else None
            position = OPTION_LETTERS.index(prev.lower())
            if nxt and OPTION_LETTERS.index(nxt.lower()) == position + 2:
                missing = OPTION_LETTERS[position + 1]
                line = f'{missing.upper() if prev.isupper() else missing}. {line}'
        out.append(line)
    return out

# A leading question number: "1. text", "12) text".
NUMBERED_LINE_RE = re.compile(r'^(\d+)[\.\)]\s*(.+)$')

# Where a numbered question starts in a theory, practical or other section:
# "1. ", "1) ", "1.Explain", "1(a)", "1 (a)", "Q1.", "Question 1" on a line
# of its own. Only "1. " and "1) " were read, so theory typed any other way
# didn't come through at all. "1.5 kg" is not a number 1.
QUESTION_NUMBER_RE = re.compile(
    r'^[ \t]*(?:'
    r'(?:question|q)[ \t]*\.?[ \t]*(?P<named>\d{1,3})[\.\):]?[ \t]*'
    r'|(?P<bare>\d{1,3})(?:[\.\)][ \t]+|[\.\)][ \t]*$|[\.\)](?=[A-Za-z(])|[ \t]*(?=\())'
    r')',
    re.IGNORECASE | re.MULTILINE
)

# The heading that introduces a trailing answer key, e.g.
# "Marking Guide (Teacher's Use)" or "Marking Scheme".
MARKING_GUIDE_RE = re.compile(
    r'(?im)^\s*(?:marking\s+(?:guide|scheme)\b.*|answer\s+key\b.*|answers\s*:?\s*)$'
)

# Where a marking guide's objective answers end: its theory part, whose
# "2. a. books" would otherwise read as question 2's answer being A.
MARKING_GUIDE_END_RE = re.compile(r'(?im)^\s*(?:section\s+[b-z]\b|theory\b)')

# A line under a question's options naming its answer: "Answer: B",
# "Ans - (c)", "Correct answer: D."
ANSWER_LINE_RE = re.compile(
    r'^(?:correct\s+)?(?:answer|ans)\s*[:\-–=]?\s*\(?([A-Ea-e])\)?\.?\s*$',
    re.IGNORECASE
)

# How an option is marked as the answer in the text: a star before or after
# it, or "(correct)". A star inside, as in "2 * 3", is maths, not a mark.
ANSWER_MARK_RE = re.compile(r'^\s*\*\s*|\s*\*\s*$|\s*\(correct\)\s*', re.IGNORECASE)

# Words that show up inside a marking-guide table/paragraph but aren't
# themselves question numbers or answer letters - skipped while scanning
# for (number, letter) pairs.
MARKING_GUIDE_SKIP_WORDS = {
    'q', 'ans', 'answer', 'answers', 'key', 'objective', 'theory',
    'section', 'correct', 'guide', "teacher's", 'teachers', 'use',
}


class ExamDocumentParser:
    """Parser for exam documents"""

    def __init__(self, file_content: bytes, file_name: str):
        self.file_content = file_content
        self.file_name = file_name
        self.warnings: List[str] = []

    def parse(self) -> Dict[str, Any]:
        """Parse document and return structured exam data"""
        file_extension = self.file_name.split('.')[-1].lower()

        if file_extension == 'pdf':
            return self._parse_pdf()
        elif file_extension in ['docx', 'doc']:
            return self._parse_word()
        elif file_extension == 'csv':
            return self._parse_csv()
        elif file_extension in ['txt', 'text']:
            return self._parse_pasted_text()
        else:
            raise ValueError(f"Unsupported file format: {file_extension}. Supported formats: PDF, Word, CSV")

    def _parse_pdf(self) -> Dict[str, Any]:
        """Parse PDF document"""
        if not PDF_AVAILABLE:
            raise ImportError("PDF parsing libraries not installed. Please install: pip install PyPDF2 pdfplumber")

        text_content = []
        images = []

        # Extract text using pdfplumber (better formatting preservation)
        try:
            with pdfplumber.open(BytesIO(self.file_content)) as pdf:
                # Validate PDF has pages
                if not pdf.pages or len(pdf.pages) == 0:
                    raise ValueError("PDF document is empty or has no pages")

                for page in pdf.pages:
                    text = page.extract_text()
                    if text:
                        text_content.append(text)

                    # Extract tables
                    tables = page.extract_tables()
                    if tables:
                        for table in tables:
                            if table and len(table) > 0:  # Validate table is not empty
                                # Convert table to HTML
                                table_html = self._convert_table_to_html(table)
                                if table_html:  # Only add if conversion succeeded
                                    text_content.append(f"\n[TABLE]\n{table_html}\n[/TABLE]\n")

        except ValueError as e:
            # Re-raise validation errors
            raise
        except Exception as e:
            self.warnings.append(f"Error extracting text from PDF: {str(e)}")
            raise ValueError(f"Failed to parse PDF document: {str(e)}")

        # Validate we extracted some content
        if not text_content:
            raise ValueError("PDF document contains no readable text content")

        # Combine all text
        full_text = "\n".join(text_content)

        # Validate full text is not empty
        if not full_text.strip():
            raise ValueError("PDF document contains no readable text after extraction")

        # Parse structured content from text
        return self._parse_text_content(full_text)

    def _parse_word(self) -> Dict[str, Any]:
        """Parse Word document"""
        if not DOCX_AVAILABLE:
            raise ImportError("Word parsing library not installed. Please install: pip install python-docx")

        try:
            doc = Document(BytesIO(self.file_content))

            if not doc.element.body:
                raise ValueError("Word document is empty or has no body content")

            # Collect all elements (paragraphs + tables) in document order
            elements = []
            for element in doc.element.body:
                try:
                    if element.tag.endswith('p'):
                        para = Paragraph(element, doc)
                        text = self._word_paragraph_text(para)
                        if text and not is_template_boilerplate(text):
                            elements.append({'type': 'paragraph', 'text': text})
                    elif element.tag.endswith('tbl'):
                        table = Table(element, doc)
                        if table.rows:
                            rows = [[c.text.strip() for c in row.cells] for row in table.rows]
                            elements.append({'type': 'table', 'rows': rows})
                except Exception as e:
                    self.warnings.append(f"Error reading element: {str(e)}")
                    continue

            if not elements:
                raise ValueError("Word document contains no readable content")

            # A marking guide at the end lists answers, not questions.
            elements, answer_key = self._split_word_marking_guide(elements)

            # Extract metadata and parse sections
            title, instructions, duration = self._extract_word_metadata(elements)
            sections = self._parse_word_sections(elements)
            if sections and answer_key:
                self._apply_answer_key(sections, answer_key)

            if not sections:
                # Fallback: join all paragraph text and use generic text parser
                plain_text = '\n'.join(e['text'] for e in elements if e['type'] == 'paragraph')
                if not plain_text.strip():
                    raise ValueError("Word document contains no readable text content")
                return self._parse_text_content(plain_text)

            total_marks = self._calculate_total_marks(sections)
            confidence = self._determine_confidence(sections)

            return {
                'title': title,
                'instructions': instructions,
                'totalMarks': total_marks,
                'durationMinutes': duration,
                'sections': sections,
                'metadata': {
                    'originalFileName': self.file_name,
                    'parsedAt': None,
                    'confidence': confidence,
                    'warnings': self.warnings
                }
            }

        except ValueError:
            raise
        except Exception as e:
            self.warnings.append(f"Error parsing Word document: {str(e)}")
            raise ValueError(f"Failed to parse Word document: {str(e)}")

    def _extract_word_metadata(self, elements: List[Dict]) -> tuple:
        """Extract title, instructions and duration from header key:value paragraphs."""
        title = "Imported Exam"
        instructions = ""
        duration = None

        # Find first section header so we only look at header content
        section_start = len(elements)
        for i, elem in enumerate(elements):
            if elem['type'] == 'paragraph':
                if re.match(r'^section\s+[a-zA-Z]\s*(?:[:\-–—]|$)', elem['text'], re.IGNORECASE):
                    section_start = i
                    break

        skip_keywords = {'exam question template', 'fill in all sections', 'how to use',
                         'tip:', 'note:', '1.', '2.', '3.', '4.', '5.'}

        for elem in elements[:section_start]:
            if elem['type'] != 'paragraph':
                continue
            text = elem['text']
            lower = text.lower()

            if any(lower.startswith(kw) for kw in skip_keywords):
                continue

            if re.match(r'^title\s*:', text, re.IGNORECASE):
                val = text.split(':', 1)[-1].strip()
                if val:
                    title = val
            elif re.match(r'^duration\s*:', text, re.IGNORECASE):
                m = re.search(r'(\d+)', text)
                if m:
                    duration = int(m.group(1))
            elif re.match(r'^instructions?\s*:', text, re.IGNORECASE):
                val = text.split(':', 1)[-1].strip()
                if val:
                    instructions = val

        # Fallback title: first line containing exam-related keywords
        if title == "Imported Exam":
            for elem in elements[:section_start]:
                if elem['type'] == 'paragraph':
                    t = elem['text']
                    if any(kw in t.lower() for kw in ['exam', 'examination', 'test', 'assessment']):
                        if len(t) > 5 and ':' not in t[:15]:
                            title = t
                            break

        return title, instructions, duration

    @staticmethod
    def _word_paragraph_text(para) -> str:
        """
        A paragraph's text, with " *" after any option line whose answer is
        bold, underlined or highlighted - the way teachers mark the correct
        answer in Word. The star is then read like a typed one.
        """
        text = para.text.strip()
        runs = para.runs
        # Runs leave out hyperlinks and the like; without every character the
        # formatting can't be lined up with the text, so leave it unmarked.
        if ''.join(run.text for run in runs).strip() != text:
            return text

        lines: List[List[Tuple[str, bool]]] = [[]]
        for run in runs:
            marked = bool(run.bold) or bool(run.underline) or run.font.highlight_color is not None
            for index, piece in enumerate(run.text.split('\n')):
                if index:
                    lines.append([])
                lines[-1].extend((char, marked) for char in piece)

        out = []
        for chars in lines:
            line = ''.join(char for char, _ in chars)
            stripped = line.strip()
            m = OPTION_LINE_RE.match(stripped)
            if m:
                start = (len(line) - len(line.lstrip())) + m.start(2)
                answer = [marked for char, marked in chars[start:] if not char.isspace()]
                if answer and all(answer):
                    stripped += ' *'
            out.append(stripped)
        return '\n'.join(out).strip()

    def _split_word_marking_guide(self, elements: List[Dict]) -> Tuple[List[Dict], Dict[int, str]]:
        """
        Take a trailing "Marking Guide" / "Answer Key" off the document's
        elements and read its answers. Nothing is taken off when no answers
        can be read from it, so no content is lost on a heading that only
        looks like one.
        """
        for index, elem in enumerate(elements):
            if elem['type'] == 'paragraph' and MARKING_GUIDE_RE.match(elem['text'].split('\n')[0]):
                guide_lines = [elem['text']]
                for rest in elements[index + 1:]:
                    if rest['type'] == 'paragraph':
                        guide_lines.append(rest['text'])
                    else:
                        guide_lines.extend(' '.join(row) for row in rest['rows'])
                _, answer_key = self._extract_marking_guide('\n'.join(guide_lines))
                if answer_key:
                    return elements[:index], answer_key
                return elements, {}
        return elements, {}

    def _parse_word_sections(self, elements: List[Dict]) -> List[Dict]:
        """Group document elements into sections, parsing each section's questions."""
        sections = []
        # Matches "SECTION A:", "SECTION A -", "SECTION A –", "SECTION A" (alone)
        header_re = re.compile(
            r'^section\s+([a-zA-Z])\s*(?:[:\-–—]\s*(.*))?$',
            re.IGNORECASE
        )

        current_letter = None
        current_type = 'custom'
        current_name = None
        current_elems: List[Dict] = []

        for elem in elements:
            if elem['type'] == 'paragraph':
                m = header_re.match(elem['text'])
                if m:
                    # Save previous section
                    if current_letter and current_elems:
                        parsed = self._parse_word_section_elements(current_name, current_type, current_elems)
                        if parsed:
                            sections.append(parsed)
                    # Start new section
                    current_letter = m.group(1).upper()
                    subtitle = (m.group(2) or '').strip().lower()
                    current_name = f'Section {current_letter}'
                    current_type = self._detect_section_type_from_subtitle(subtitle)
                    current_elems = []
                    continue

            if current_letter is not None:
                current_elems.append(elem)

        # Flush last section
        if current_letter and current_elems:
            parsed = self._parse_word_section_elements(current_name, current_type, current_elems)
            if parsed:
                sections.append(parsed)

        return sections

    def _detect_section_type_from_subtitle(self, subtitle: str) -> str:
        if 'subjective' in subtitle:  # holds "objective"
            return 'theory'
        if any(kw in subtitle for kw in ['objective', 'multiple choice', 'mcq', 'choose']):
            return 'objective'
        if any(kw in subtitle for kw in ['theory', 'essay', 'short answer', 'long answer']):
            return 'theory'
        if any(kw in subtitle for kw in ['practical', 'experiment', 'lab']):
            return 'practical'
        return 'custom'

    def _parse_word_section_elements(self, name: str, section_type: str, elements: List[Dict]) -> Optional[Dict]:
        """Parse questions from a section's elements (tables and/or paragraphs)."""
        questions: List[Dict] = []
        instructions = ''
        plain_lines: List[str] = []

        instr_re = re.compile(
            r'^(?:section\s+[a-zA-Z]\s+)?instructions?\s*(?:\(optional\))?\s*:',
            re.IGNORECASE
        )

        for elem in elements:
            if elem['type'] == 'table':
                table_qs = self._parse_question_table(elem['rows'])
                if table_qs:
                    questions.extend(table_qs)
            elif elem['type'] == 'paragraph':
                text = elem['text']
                if instr_re.match(text):
                    instructions = text.split(':', 1)[-1].strip()
                else:
                    plain_lines.append(text)

        # If no table questions, parse plain text
        if not questions and plain_lines:
            plain_text = '\n'.join(self._fold_answer_lines('\n'.join(plain_lines).splitlines()))
            if section_type == 'practical':
                questions = self._parse_practical_text(plain_text)
            else:
                questions = self._extract_questions(plain_text, section_type)

            # Objective questions numbered by Word's own list numbering have
            # no "1." in their text, so the numbered reader above finds none
            # and the whole section was dropped. Read them the way pasted
            # text is read instead: a question, then its A./B./C./D. lines.
            if section_type == 'objective':
                lines = [l.strip() for l in plain_text.splitlines() if l.strip()]
                lead_instruction = self._objective_lead_instruction(lines)
                if lead_instruction:
                    lines = lines[1:]
                unnumbered = self._extract_objective_from_paragraphs(lines)
                if len(unnumbered) > len(questions):
                    questions = unnumbered
                    if lead_instruction and not instructions:
                        instructions = lead_instruction

        if not questions:
            return None

        return {
            'type': section_type,
            'name': name,
            'instructions': instructions,
            'questions': questions
        }

    @staticmethod
    def _objective_lead_instruction(lines: List[str]) -> str:
        """
        The section's opening line when it is an instruction such as "Choose
        the correct answer." rather than a question - otherwise it would be
        read as the start of the first question. A question that begins
        "Choose..." is followed by its options; an instruction is not.
        """
        if len(lines) < 2:
            return ''
        lead = lines[0]
        if OPTION_LINE_RE.match(lead) or NUMBERED_LINE_RE.match(lead) or OPTION_LINE_RE.match(lines[1]):
            return ''
        if lead.lower().startswith(('choose', 'select', 'answer', 'instruction', 'read ', 'pick')):
            return lead
        return ''

    def _parse_question_table(self, rows: List[List[str]]) -> List[Dict]:
        """Parse a Word table where each row is a question.

        Expects a header row with columns like:
        #, Question, Option A, Option B, Option C, Option D, Correct, Marks
        """
        if not rows or len(rows) < 2:
            return []

        header = [h.lower().strip() for h in rows[0]]

        # Must have a Question column to be treated as a question table
        if not any('question' in h for h in header):
            return []

        def find_col(*patterns: str) -> int:
            # Exact match first
            for pat in patterns:
                for i, h in enumerate(header):
                    if h == pat:
                        return i
            # Contains match
            for pat in patterns:
                for i, h in enumerate(header):
                    if pat in h:
                        return i
            return -1

        q_col     = find_col('question')
        a_col     = find_col('option a', 'opta', 'opt a')
        b_col     = find_col('option b', 'optb', 'opt b')
        c_col     = find_col('option c', 'optc', 'opt c')
        d_col     = find_col('option d', 'optd', 'opt d')
        e_col     = find_col('option e', 'opte', 'opt e')
        correct_col = find_col('correct', 'answer', 'key')
        marks_col   = find_col('marks', 'mark', 'score', 'points')

        questions = []
        for row in rows[1:]:
            if q_col < 0 or q_col >= len(row):
                continue
            question_text = row[q_col].strip()
            if not question_text:
                continue

            options: Dict[str, str] = {}
            for col, key in [
                (a_col, 'optionA'), (b_col, 'optionB'),
                (c_col, 'optionC'), (d_col, 'optionD'), (e_col, 'optionE')
            ]:
                if col >= 0 and col < len(row) and row[col].strip():
                    options[key] = row[col].strip()

            correct = ''
            if correct_col >= 0 and correct_col < len(row):
                raw = row[correct_col].strip().upper()
                if raw in ('A', 'B', 'C', 'D', 'E'):
                    correct = raw
                elif raw and raw not in ('CORRECT', 'ANSWER', 'KEY'):
                    self.warnings.append(
                        f"Unrecognized correct answer '{raw}' for: {question_text[:50]}"
                    )

            marks = 1
            if marks_col >= 0 and marks_col < len(row) and row[marks_col].strip():
                try:
                    marks = max(1, int(row[marks_col].strip()))
                except (ValueError, TypeError):
                    marks = 1

            if len(options) >= 2:
                questions.append({
                    'question': self._clean_html(question_text),
                    'type': 'objective',
                    'options': options,
                    'correctAnswer': correct,
                    'marks': marks
                })
            else:
                questions.append({
                    'question': self._clean_html(question_text),
                    'type': 'theory',
                    'marks': marks
                })

        return questions

    def _parse_practical_text(self, text: str) -> List[Dict]:
        """Parse practical questions in the 'Practical N / Task: / Marks:' format."""
        questions: List[Dict] = []

        # Split on "Practical N" headers; block[0] is pre-header text (notes/instructions) — skip it
        blocks = re.split(r'(?im)^\s*practical\s+\d+\s*$', text)
        practical_blocks = blocks[1:] if len(blocks) > 1 else blocks

        for block in practical_blocks:
            block = block.strip()
            if not block:
                continue

            task_m = re.search(
                r'(?i)task\s*:\s*(.+?)(?=\n\s*(?:materials?|time\s+allowed|expected|marks?)\s*:|$)',
                block, re.DOTALL
            )
            marks_m = re.search(r'(?i)marks?\s*:\s*(\d+)', block)

            task = task_m.group(1).strip() if task_m else block
            marks = int(marks_m.group(1)) if marks_m else 1

            if task:
                questions.append({
                    'question': self._clean_html(task),
                    'type': 'practical',
                    'marks': marks
                })

        # Fallback to generic extraction
        if not questions and text.strip():
            questions = self._extract_questions(text, 'practical')

        return questions

    @staticmethod
    def _strip_to_csv_header(text: str) -> str:
        """
        Drop comment and blank lines that appear above the column headers.

        The template generator writes '#'-prefixed guidance rows above the
        header, and teachers often leave notes of their own at the top. The
        header is the first line that names a 'question' column.
        """
        lines = text.splitlines()
        for index, line in enumerate(lines):
            stripped = line.strip()
            if not stripped or stripped.startswith('#'):
                continue
            cells = [c.strip().strip('"').lower() for c in stripped.split(',')]
            if 'question' in cells:
                return "\n".join(lines[index:])
            # A non-comment line that is not the header means the file starts
            # with data — leave it alone and let the normal validation speak.
            break
        return text

    def _parse_csv(self) -> Dict[str, Any]:
        """Parse CSV document

        Expected CSV format:
        Section,Type,Question,OptionA,OptionB,OptionC,OptionD,OptionE,CorrectAnswer,Marks,ExpectedPoints,Instructions

        Where:
        - Section: Section name (Objective, Theory, Practical, or custom name)
        - Type: objective, theory, practical, or custom
        - Question: Question text
        - OptionA-E: Multiple choice options (for objective questions)
        - CorrectAnswer: Correct option letter (for objective questions)
        - Marks: Question marks/points
        - ExpectedPoints: Expected answer points (for theory/practical)
        - Instructions: Section-specific instructions (optional)

        First row with Section="EXAM_INFO" can contain exam metadata
        """
        try:
            # utf-8-sig strips the BOM Excel and Google Sheets write, which
            # would otherwise end up glued to the first column name.
            text_content = self.file_content.decode('utf-8-sig')
        except UnicodeDecodeError:
            try:
                # Try with latin-1 encoding as fallback
                text_content = self.file_content.decode('latin-1')
                self.warnings.append("CSV file encoding is not UTF-8. Using latin-1 encoding.")
            except Exception as e:
                raise ValueError(f"Cannot decode CSV file. Please ensure it's saved as UTF-8 or latin-1 encoding: {str(e)}")

        # Validate CSV has content
        if not text_content or not text_content.strip():
            raise ValueError("CSV file is empty")

        # The downloadable template carries '#' guidance lines above the header,
        # and teachers add notes of their own. Scan for the real header row
        # instead of assuming line 1, the way the other bulk importers do.
        text_content = self._strip_to_csv_header(text_content)

        try:
            # Parse CSV
            csv_reader = csv.DictReader(StringIO(text_content))

            # Validate CSV has required columns
            if not csv_reader.fieldnames:
                raise ValueError("CSV file has no headers. Please include column headers.")

            # Required columns (at least one of these must exist)
            if 'Question' not in csv_reader.fieldnames and 'question' not in csv_reader.fieldnames:
                raise ValueError("CSV file must have a 'Question' column")

            # Normalize field names to lowercase for case-insensitive matching
            rows = []
            for row in csv_reader:
                normalized_row = {k.lower().strip(): v for k, v in row.items() if k}
                rows.append(normalized_row)

            # Validate we have rows
            if not rows:
                raise ValueError("CSV file contains no data rows")

            # Extract exam metadata from first row if present
            exam_title = "Imported Exam"
            exam_instructions = ""
            exam_duration = None

            if rows[0].get('section', '').upper() == 'EXAM_INFO':
                metadata_row = rows.pop(0)
                exam_title = metadata_row.get('question', exam_title) or exam_title
                exam_instructions = metadata_row.get('instructions', exam_instructions) or exam_instructions
                try:
                    duration_str = metadata_row.get('marks', '') or metadata_row.get('duration', '')
                    if duration_str:
                        exam_duration = int(duration_str)
                except (ValueError, TypeError):
                    pass

            # Group rows by section
            sections_dict = {}
            for row in rows:
                # Get section name (default to 'Main Section')
                section_name = row.get('section', 'Main Section').strip() or 'Main Section'

                # Get question type (default to 'theory')
                question_type = row.get('type', 'theory').lower().strip() or 'theory'
                if question_type not in ['objective', 'theory', 'practical', 'custom']:
                    self.warnings.append(f"Unknown question type '{question_type}', treating as 'custom'")
                    question_type = 'custom'

                # Create section key
                section_key = f"{section_name}|{question_type}"

                if section_key not in sections_dict:
                    sections_dict[section_key] = {
                        'name': section_name,
                        'type': question_type,
                        'instructions': row.get('instructions', '').strip(),
                        'questions': []
                    }

                # Parse question based on type
                question_data = self._parse_csv_question(row, question_type)

                if question_data:
                    sections_dict[section_key]['questions'].append(question_data)

            # Convert sections dict to list
            sections = list(sections_dict.values())

            # Validate we have at least one section with questions
            if not sections:
                raise ValueError("No valid sections found in CSV file")

            # Calculate total marks
            total_marks = self._calculate_total_marks(sections)

            # Determine confidence (CSV parsing is always high confidence if successful)
            confidence = 'high' if all(len(s['questions']) > 0 for s in sections) else 'medium'

            return {
                'title': exam_title,
                'instructions': exam_instructions,
                'totalMarks': total_marks,
                'durationMinutes': exam_duration,
                'sections': sections,
                'metadata': {
                    'originalFileName': self.file_name,
                    'parsedAt': None,  # Set by view
                    'confidence': confidence,
                    'warnings': self.warnings
                }
            }

        except csv.Error as e:
            raise ValueError(f"Invalid CSV format: {str(e)}")
        except Exception as e:
            if isinstance(e, ValueError):
                raise
            raise ValueError(f"Failed to parse CSV file: {str(e)}")

    def _parse_csv_question(self, row: Dict[str, str], question_type: str) -> Optional[Dict[str, Any]]:
        """Parse a single CSV row into a question"""
        question_text = row.get('question', '').strip()

        # Validate question text exists
        if not question_text:
            self.warnings.append("Skipping row with empty question text")
            return None

        # Extract marks
        marks = 1
        marks_str = row.get('marks', '1').strip()
        if marks_str:
            try:
                marks = int(marks_str)
                if marks < 1 or marks > 100:
                    self.warnings.append(f"Unusual mark value: {marks}. Using default of 1.")
                    marks = 1
            except ValueError:
                self.warnings.append(f"Invalid marks value '{marks_str}'. Using default of 1.")
                marks = 1

        if question_type == 'objective':
            # Extract options
            options = {}
            for letter in ['a', 'b', 'c', 'd', 'e']:
                option_key = f'option{letter}'
                option_value = row.get(option_key, '').strip()
                if option_value:
                    options[option_key] = option_value

            # Validate at least 2 options
            if len(options) < 2:
                self.warnings.append(f"Objective question has fewer than 2 options: {question_text[:50]}...")

            # Get correct answer
            correct_answer = row.get('correctanswer', '').strip().upper() or row.get('answer', '').strip().upper()
            if correct_answer and correct_answer not in ['A', 'B', 'C', 'D', 'E']:
                self.warnings.append(f"Invalid correct answer '{correct_answer}'. Expected A, B, C, D, or E.")
                correct_answer = ''

            return {
                'question': f'<p>{self._escape_html(question_text)}</p>',
                'type': 'objective',
                'options': options,
                'correctAnswer': correct_answer,
                'marks': marks
            }

        elif question_type == 'theory':
            expected_points = row.get('expectedpoints', '').strip() or row.get('expected', '').strip()

            return {
                'question': f'<p>{self._escape_html(question_text)}</p>',
                'type': 'theory',
                'marks': marks,
                'expectedPoints': expected_points,
                'subQuestions': []  # CSV doesn't support nested sub-questions in simple format
            }

        elif question_type == 'practical':
            expected_outcome = row.get('expectedpoints', '').strip() or row.get('expected', '').strip()

            return {
                'question': f'<p>{self._escape_html(question_text)}</p>',
                'type': 'practical',
                'marks': marks,
                'expectedPoints': expected_outcome
            }

        else:  # custom
            return {
                'question': f'<p>{self._escape_html(question_text)}</p>',
                'type': 'custom',
                'marks': marks
            }

    def _escape_html(self, text: str) -> str:
        """Escape HTML special characters"""
        if not text:
            return ''
        return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

    # -----------------------------------------------------------------
    # Pasted-text parsing
    #
    # A teacher pasting an exam straight from Word/Google Docs into a
    # textarea gets plain text where every paragraph - even a single
    # heading or a lone "A. option" line - lands on its own line,
    # separated by a blank line. That's different enough from the
    # PDF/Word extraction above (which keeps real line breaks and often
    # numbers every question) to need its own section/question detector:
    # objective questions here usually have no leading "1." at all, just
    # a question paragraph immediately followed by "A./B./C./D." lines.
    # -----------------------------------------------------------------

    def _parse_pasted_text(self) -> Dict[str, Any]:
        """Parse raw pasted exam text (no numbering required on MCQs)."""
        try:
            text = self.file_content.decode('utf-8-sig')
        except UnicodeDecodeError:
            text = self.file_content.decode('utf-8', errors='ignore')

        if not text or not text.strip():
            raise ValueError("Pasted text is empty.")

        lines = [l for l in text.splitlines() if not is_template_boilerplate(l)]
        text = '\n'.join(lines)

        # A trailing "Marking Guide" table of objective answers isn't exam
        # content - pull it out before section/question detection sees it.
        text, answer_key = self._extract_marking_guide(text)

        title = self._extract_title(text)
        instructions = self._extract_instructions(text)
        sections = self._detect_sections_from_paragraphs(text, title=title)

        if answer_key:
            self._apply_answer_key(sections, answer_key)

        if not sections:
            raise ValueError(
                "Could not find any questions in the pasted text. Put each "
                "question on its own paragraph, and for multiple-choice "
                "questions list the options as A., B., C., D. each on their "
                "own line right after the question."
            )

        total_marks = self._calculate_total_marks(sections)
        confidence = self._determine_confidence(sections)

        return {
            'title': title,
            'instructions': instructions,
            'totalMarks': total_marks,
            'durationMinutes': None,
            'sections': sections,
            'metadata': {
                'originalFileName': self.file_name,
                'parsedAt': None,
                'confidence': confidence,
                'warnings': self.warnings
            }
        }

    def _split_into_paragraphs(self, text: str) -> List[str]:
        """
        Return one entry per non-blank line.

        Pasted exam text shows up in two common shapes: a blank line after
        every single line (typical of copying out of Word/Google Docs into a
        plain textarea), or ordinary single-newline-per-line text with no
        blank lines at all (typical of a PDF copy or a teacher typing
        straight into the box). Splitting on individual lines handles both
        the same way - blank lines just disappear as empty entries.
        """
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        return [part for line in lines for part in split_inline_options(line)]

    def _extract_marking_guide(self, text: str) -> Tuple[str, Dict[int, str]]:
        """
        Split a trailing "Marking Guide" answer key off the main text.

        Handles the messy shape a pasted Word table takes once it's flattened
        to plain text (each cell - including a lone "Q" or "Ans" header, or
        even a stray tab character - lands on its own line). Regardless of
        how many columns the table had, reading the flattened cells in order
        and pairing each question number with the token right after it
        recovers the right answers, because the pairing is keyed by the
        question number itself, not by position in the table.
        """
        m = MARKING_GUIDE_RE.search(text)
        if not m:
            return text, {}

        body_text = text[:m.start()]
        remainder = text[m.end():]
        # Only the objective answers: a theory part's "2. a. books" would
        # otherwise read as question 2's answer being A.
        end = MARKING_GUIDE_END_RE.search(remainder)
        if end:
            remainder = remainder[:end.start()]

        # "1. B", "1) B", "1-B", "1.B" and "1 B" all pair a number with a letter.
        tokens = re.split(r"[\s\-–—:.,()\[\]]+", remainder)
        tokens = [t for t in tokens if t and t.lower() not in MARKING_GUIDE_SKIP_WORDS]

        answer_key: Dict[int, str] = {}
        i = 0
        while i < len(tokens) - 1:
            num_tok, ans_tok = tokens[i], tokens[i + 1]
            if num_tok.isdigit() and re.match(r'^[A-Ea-e]$', ans_tok):
                answer_key.setdefault(int(num_tok), ans_tok.upper())
                i += 2
            else:
                i += 1

        if not answer_key:
            # Heading was found but nothing usable followed it - leave the
            # text untouched rather than silently dropping that content.
            return text, {}

        return body_text, answer_key

    def _apply_answer_key(self, sections: List[Dict[str, Any]], answer_key: Dict[int, str]) -> None:
        """Fill in objective correctAnswer from the marking guide, matching
        each question by its 1-based position within its section."""
        applied = 0
        for section in sections:
            if section.get('type') != 'objective':
                continue
            for position, question in enumerate(section['questions'], start=1):
                if question.get('correctAnswer'):
                    continue  # already found inline (e.g. marked with *)
                answer = answer_key.get(position)
                if answer:
                    question['correctAnswer'] = answer
                    applied += 1

        if applied:
            self.warnings.append(
                f"Applied {applied} answer(s) from the marking guide to the objective questions."
            )
        else:
            self.warnings.append(
                "Found a marking guide but couldn't match its answers to the "
                "objective questions - please double-check the correct answers."
            )

    def _detect_sections_from_paragraphs(self, text: str, title: str = '') -> List[Dict[str, Any]]:
        """Group pasted-text paragraphs into sections and parse their questions."""
        paras = self._fold_answer_lines(self._split_into_paragraphs(text))
        if not paras:
            return []

        # When there's no section heading to scope questions to (see the
        # fallback below), the title line would otherwise sit directly in
        # front of the first question with nothing to separate them and get
        # read as part of its stem - drop it, since it's already captured
        # separately as the exam title.
        # The title falls back to the first long line, which can just as well
        # be "Section A", a numbered question, or the stem above a question's
        # options. Dropping those lost Section A, or the first question, from
        # a paper typed with no title at the top.
        title_norm = title.strip()
        if (
            title_norm and paras and paras[0] == title_norm
            and not section_heading(paras[0])
            and not NUMBERED_LINE_RE.match(paras[0])
            and not (len(paras) > 1 and OPTION_LINE_RE.match(paras[1]))
        ):
            paras = paras[1:]

        headings = self._section_headings(paras)
        sections: List[Dict[str, Any]] = []

        if not headings:
            # No headings anywhere - one section, objective or theory by
            # what its lines look like.
            self._read_section('Main Section', '', paras, sections, untitled=True)
            if len(sections) == 1:
                self.warnings.append(
                    "No 'Section A/B' headings found. All questions grouped into one section."
                )
            return sections

        # Objective questions typed above the first heading, on a paper that
        # heads only its theory: they were dropped with the school's name.
        preamble = paras[:headings[0][0]]
        if any(OPTION_LINE_RE.match(p) for p in mend_objective_lines(preamble)):
            self._read_section('Main Section', '', preamble, sections, untitled=True)

        for k, (idx, width, name, subtitle) in enumerate(headings):
            end = headings[k + 1][0] if k + 1 < len(headings) else len(paras)
            self._read_section(name, subtitle, paras[idx + width:end], sections)

        return sections

    @staticmethod
    def _section_headings(paras: List[str]) -> List[Tuple[int, int, str, str]]:
        """
        (index, lines it takes, name, subtitle) of each section heading.

        A heading straight after another is a table of contents naming the
        sections, not one starting - except "SECTION B" over "THEORY", which
        is one heading on two lines.
        """
        found: List[Tuple[int, int, str, str]] = []
        idx = 0
        while idx < len(paras):
            heading = section_heading(paras[idx])
            if not heading:
                idx += 1
                continue
            name, subtitle = heading
            width = 1
            nxt = paras[idx + 1] if idx + 1 < len(paras) else ''
            if section_heading(nxt):
                is_section = SECTION_HEADER_RE.match(paras[idx].strip())
                if is_section and not subtitle and KIND_HEADING_RE.match(nxt.strip()):
                    subtitle = nxt.strip()
                    name = f'{name}: {subtitle}'
                    width = 2
                else:
                    idx += 1
                    continue
            found.append((idx, width, name, subtitle))
            idx += width
        return found

    @staticmethod
    def _option_runs(lines: List[str]) -> List[int]:
        """How many options each question has, for the questions in these lines."""
        runs: List[int] = []
        prev: Optional[str] = None
        for line in lines:
            letter = _option_letter(line)
            if letter and prev is not None and not options_restart(prev, letter):
                runs[-1] += 1
            elif letter:
                runs.append(1)
            prev = letter
        return runs

    def _infer_section_type(self, subtitle: str, body: List[str]) -> str:
        """
        A section's kind from its heading, or from its lines when the
        heading doesn't say: "Section A" over options is objective, and
        "Section B" over numbered questions is theory. Both were 'custom',
        which kept no options and no theory section.
        """
        section_type = self._detect_section_type_from_subtitle(subtitle.lower())
        if section_type != 'custom':
            return section_type
        intro = ' '.join(body[:2]).lower()
        if any(kw in intro for kw in ('answer any', 'attempt', 'essay', 'theory')):
            return 'theory'
        runs = [r for r in self._option_runs(mend_objective_lines(body)) if r >= 2]
        numbered = sum(1 for s in body if NUMBERED_LINE_RE.match(s))
        if runs and sum(1 for r in runs if r >= 3) * 2 >= len(runs) and len(runs) * 2 >= numbered:
            return 'objective'
        # A heading naming something else, "Section C: Comprehension", keeps its own section.
        return 'custom' if subtitle else 'theory'

    def _read_section(
        self, name: str, subtitle: str, body: List[str], sections: List[Dict[str, Any]],
        untitled: bool = False,
    ) -> None:
        """
        Read one section's lines and add it to sections, telling the teacher
        about any question left out, or the section itself when nothing in
        it could be read.
        """
        section_type = self._infer_section_type(subtitle, body)

        instructions = ''
        passage = ''
        if body:
            lead = body[0]
            lead_lower = lead.lower()
            looks_like_instruction = (
                not OPTION_LINE_RE.match(lead)
                and not NUMBERED_LINE_RE.match(lead)
                and any(lead_lower.startswith(kw) for kw in
                        ('choose', 'select', 'answer', 'attempt', 'instruction', 'read '))
            )
            if looks_like_instruction:
                instructions = lead
                body = body[1:]

        label = 'the paper' if untitled else name
        rest: List[str] = []
        if section_type == 'objective':
            lead_lines: List[str] = []
            skipped: List[str] = []
            questions = self._extract_objective_from_paragraphs(
                body, lead_out=lead_lines, skipped_out=skipped, rest_out=rest)
            # A comprehension passage, or an instruction, above the first
            # question belongs to the section, not to question 1.
            instruction_lines, passage_lines = split_passage([instructions, *lead_lines])
            if untitled:
                # Above an untitled paper's first question is the school's
                # name and the paper's title, not instructions.
                instruction_lines = [l for l in instruction_lines if l == instructions]
            instructions = '\n'.join(instruction_lines)
            passage = '\n'.join(passage_lines)
            for text in skipped:
                self.warnings.append(
                    f"Left out{'' if untitled else f' of {name}'}: \"{text[:80]}\" - an objective "
                    "question needs at least two options typed as A., B., C., D. on their own "
                    "lines under it."
                )
        else:
            text = '\n'.join(body)
            first = QUESTION_NUMBER_RE.search(text)
            if first and text[:first.start()].strip():
                # Lines above the first question, "Answer any three", are
                # the section's instructions rather than nothing at all.
                instructions = '\n'.join(filter(None, [instructions, text[:first.start()].strip()]))
            questions = self._extract_questions(text, section_type)
            if not questions and body and section_type == 'theory':
                # Theory typed without numbers: each line is a question.
                questions = [q for q in (self._extract_questions(f'1. {line}', section_type) for line in body)
                             for q in q]
                if questions:
                    self.warnings.append(
                        f"The questions in {label} aren't numbered 1., 2., 3., so each line was taken "
                        "as one question - check them over."
                    )

        if questions:
            sections.append({
                'type': section_type,
                # The whole heading, "Section B: LITERARY APPRECIATION -
                # Choose the best option", which a later section's first
                # question is shown under once sections are joined.
                'name': name,
                'instructions': instructions,
                'passage': passage,
                'questions': questions
            })
        elif not untitled:
            self.warnings.append(
                f"No questions could be read from \"{name}\", so it was left out. Number its "
                "questions 1., 2., 3., and for objective questions put the options A., B., C., D. "
                "on their own lines."
            )

        if rest:
            if any(QUESTION_NUMBER_RE.match(line) for line in rest):
                self.warnings.append(
                    "The questions numbered from 1 again after the objective questions were read "
                    "as a section of their own, as there is no heading such as SECTION B or THEORY "
                    "over them - check that they came through as you meant."
                )
                self._read_section('', '', rest, sections, untitled=True)
            elif any(line.rstrip().endswith('?') for line in rest):
                self.warnings.append(
                    f"Skipped after the last question in {label}: \"{' '.join(rest)[:80]}\" - "
                    "it has no options A., B., C., D. under it."
                )

    @staticmethod
    def _numbered_chain(stem_lines: List[str], last_number: Optional[int]) -> List[int]:
        """
        Where the questions numbered in a run of lines start: each numbered
        line that counts on from the question before. A question whose
        options were left off runs into the next question's lines, "5. ..."
        then "6. ...", and was read as a lead-in to question 6. Statements
        numbered inside a question, "1. Lagos is..." under question 7, don't
        count on from 6, so they stay part of it.
        """
        chain: List[Tuple[int, int]] = []
        for p, line in enumerate(stem_lines):
            m = NUMBERED_LINE_RE.match(line)
            if not m:
                continue
            number = int(m.group(1))
            before = chain[-1][1] if chain else last_number
            if before is None or before < number <= before + 3:
                chain.append((p, number))
        return [p for p, _ in chain]

    def _extract_objective_from_paragraphs(
        self, lines: List[str], lead_out: Optional[List[str]] = None,
        skipped_out: Optional[List[str]] = None, rest_out: Optional[List[str]] = None,
    ) -> List[Dict[str, Any]]:
        """
        Extract MCQ questions from a list of lines, whether or not the
        question itself is numbered. A run of one or more non-option lines
        followed by two or more "A./B./C./D." lines is treated as one
        objective question - the whole run becomes the question stem, so a
        stem that happens to wrap across more than one line still comes
        through as a single question instead of being split apart.

        skipped_out receives a short description of each question left out
        because it had no options, and each set of options with no question,
        so the teacher can be told. rest_out, when given, receives the lines
        from where the numbering starts again at 1 - a theory section with
        no heading of its own - and the lines after the last question.
        """
        lines = mend_objective_lines(lines)
        questions: List[Dict[str, Any]] = []
        last_number: Optional[int] = None
        i = 0
        n = len(lines)

        def skip(texts: List[str]) -> None:
            if skipped_out is not None and texts:
                skipped_out.append(' '.join(texts))

        while i < n:
            if OPTION_LINE_RE.match(lines[i]):
                # Options with no question above them.
                k = i
                while k < n and OPTION_LINE_RE.match(lines[k]):
                    k += 1
                skip(['Options with no question:'] + lines[i:k])
                i = k
                continue

            j = i
            while j < n and not OPTION_LINE_RE.match(lines[j]):
                j += 1
            # lines[i:j] are candidate stem lines; lines[j] starts an option run (or is past the end)

            # Numbering that starts again at 1 after a few questions is a new
            # section, with no heading for it: theory typed under the
            # objectives. Read as more objective questions, it was lost.
            # Only a "1." that is the first numbered line after the last
            # options: "1. Lagos is..." under "7. Consider these:" is a
            # statement inside question 7.
            if rest_out is not None and last_number and last_number >= 2:
                first = next((p for p in range(i, j) if NUMBERED_LINE_RE.match(lines[p])), None)
                if first is not None and int(NUMBERED_LINE_RE.match(lines[first]).group(1)) == 1:
                    rest_out.extend(lines[i:])
                    return questions

            option_lines: List[str] = []
            k = j
            while k < n and OPTION_LINE_RE.match(lines[k]):
                if option_lines and options_restart(_option_letter(option_lines[-1]), _option_letter(lines[k])):
                    break  # "A." again: the next question's options
                option_lines.append(lines[k])
                k += 1

            if len(option_lines) < 2:
                if j >= n:
                    if rest_out is not None:
                        rest_out.extend(lines[i:j])
                    elif any(NUMBERED_LINE_RE.match(s) or s.rstrip().endswith('?') for s in lines[i:j]):
                        skip(lines[i:j])
                else:
                    skip(lines[i:k])
                i = k
                continue

            stem_lines = lines[i:j]
            # Lines before a numbered question are not its text: a passage,
            # or an "INSTRUCTION: choose the word nearest in meaning" over
            # the questions that follow. Above the first question they go to
            # the section (lead_out); further down they stay with the
            # question they introduce, on lines of their own. Questions
            # numbered among them had no options and are left out.
            lead: List[str] = []
            chain = self._numbered_chain(stem_lines, last_number) or [
                p for p, s in enumerate(stem_lines) if p and NUMBERED_LINE_RE.match(s)][:1]
            if chain and chain[-1] > 0:
                for a, b in zip(chain, chain[1:]):
                    skip(stem_lines[a:b])
                lead, stem_lines = stem_lines[:chain[0]], stem_lines[chain[-1]:]
                if not questions and lead_out is not None:
                    lead_out.extend(lead)
                    lead = []
            num_m = NUMBERED_LINE_RE.match(stem_lines[0])
            if num_m:
                last_number = int(num_m.group(1))
                stem_lines = [num_m.group(2).strip()] + stem_lines[1:]
            stem_text = ' '.join(s for s in stem_lines if s)
            if lead:
                stem_text = '\n'.join(lead) + '\n\n' + stem_text

            options, correct_answer = self._options_and_answer(
                [OPTION_LINE_RE.match(opt_line).groups() for opt_line in option_lines], stem_text)

            questions.append({
                'question': self._clean_html(stem_text),
                'type': 'objective',
                'options': options,
                'correctAnswer': correct_answer,
                'marks': self._extract_marks(stem_text)
            })
            i = k

        return questions

    def _parse_text_content(self, text: str) -> Dict[str, Any]:
        """Parse text content and extract exam structure"""

        # Answers given in a marking guide or on "Answer: B" lines, as in
        # pasted text and Word.
        text, answer_key = self._extract_marking_guide(text)
        text = '\n'.join(self._fold_answer_lines(text.splitlines()))

        # Extract exam title (usually first non-empty line or line with "EXAM" keyword)
        title = self._extract_title(text)

        # Extract general instructions
        instructions = self._extract_instructions(text)

        # Detect sections
        sections = self._detect_sections(text)
        if sections and answer_key:
            self._apply_answer_key(sections, answer_key)

        # Calculate total marks
        total_marks = self._calculate_total_marks(sections)

        # Determine confidence level
        confidence = self._determine_confidence(sections)

        return {
            'title': title,
            'instructions': instructions,
            'totalMarks': total_marks,
            'durationMinutes': None,  # Usually needs manual input
            'sections': sections,
            'metadata': {
                'originalFileName': self.file_name,
                'parsedAt': None,  # Set by view
                'confidence': confidence,
                'warnings': self.warnings
            }
        }

    def _extract_title(self, text: str) -> str:
        """Extract exam title from text"""
        lines = [l.strip() for l in text.split('\n') if l.strip()]

        # Look for lines containing exam-related keywords
        exam_keywords = ['exam', 'test', 'quiz', 'assessment', 'examination']

        for line in lines[:10]:  # Check first 10 lines
            lower_line = line.lower()
            if any(keyword in lower_line for keyword in exam_keywords):
                return line

        # Fallback: use first substantial line
        for line in lines:
            if len(line) > 10 and not line.isdigit():
                return line

        return "Imported Exam"

    def _extract_instructions(self, text: str) -> str:
        """Extract general instructions"""
        # Look for instruction patterns
        instruction_patterns = [
            r'instructions?:?\s*\n(.*?)(?:\n\n|section\s+[a-z]|question\s+\d)',
            r'general\s+instructions?:?\s*\n(.*?)(?:\n\n|section\s+[a-z])',
            r'read\s+the\s+following.*?:?\s*\n(.*?)(?:\n\n|section\s+[a-z])'
        ]

        for pattern in instruction_patterns:
            match = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
            if match:
                return match.group(1).strip()

        return ""

    def _detect_sections(self, text: str) -> List[Dict[str, Any]]:
        """Detect exam sections and questions"""
        sections = []

        # Common section headers
        section_patterns = {
            'objective': r'section\s*[a-z]?:?\s*objective|multiple\s*choice|choose\s*the\s*correct',
            'theory': r'section\s*[b-z]?:?\s*theory|essay|short\s*answer|answer\s*the\s*following',
            'practical': r'section\s*[c-z]?:?\s*practical|experiment|practical\s*work'
        }

        # Split text by major section markers
        section_splits = re.split(
            r'\n\s*section\s*[a-z][\s:]+',
            text,
            flags=re.IGNORECASE
        )

        for i, section_text in enumerate(section_splits):
            if not section_text.strip() or i == 0:
                continue

            # Determine section type
            section_type = 'custom'
            section_name = f'Section {chr(64 + i)}'  # A, B, C...

            for stype, pattern in section_patterns.items():
                if re.search(pattern, section_text[:200], re.IGNORECASE):
                    section_type = stype
                    section_name = stype.capitalize()
                    break

            # Extract section instructions
            section_instructions = self._extract_section_instructions(section_text)

            # Extract questions
            questions = self._extract_questions(section_text, section_type)

            if questions:
                sections.append({
                    'type': section_type,
                    'name': section_name,
                    'instructions': section_instructions,
                    'questions': questions
                })

        # If no sections detected, treat entire document as one section
        if not sections:
            questions = self._extract_questions(text, 'theory')
            if questions:
                sections.append({
                    'type': 'theory',
                    'name': 'Main Section',
                    'instructions': '',
                    'questions': questions
                })
                self.warnings.append("No clear section divisions found. All questions grouped into one section.")

        return sections

    def _extract_section_instructions(self, section_text: str) -> str:
        """Extract instructions specific to a section"""
        lines = section_text.split('\n')
        instructions_lines = []

        # Instructions usually appear before first question
        for line in lines[:10]:
            line = line.strip()
            # Stop when we hit a question number
            if re.match(r'^\d+[\.\)]\s+', line):
                break
            if line and not line.isdigit():
                instructions_lines.append(line)

        return ' '.join(instructions_lines)

    def _extract_questions(self, text: str, section_type: str) -> List[Dict[str, Any]]:
        """Extract questions from section text"""
        questions = []

        starts = list(QUESTION_NUMBER_RE.finditer(text))
        for n, start in enumerate(starts):
            end = starts[n + 1].start() if n + 1 < len(starts) else len(text)
            question_content = text[start.end():end].strip()

            if not question_content:
                continue

            # Parse based on section type
            if section_type == 'objective':
                question_data = self._parse_objective_question(question_content)
            elif section_type == 'theory':
                question_data = self._parse_theory_question(question_content)
            elif section_type == 'practical':
                question_data = self._parse_practical_question(question_content)
            else:
                question_data = self._parse_generic_question(question_content)

            if question_data:
                questions.append(question_data)

        return questions

    def _options_and_answer(self, pairs, stem: str) -> Tuple[Dict[str, str], Optional[str]]:
        """
        A question's options from (letter, text) pairs, and its answer: the
        one option marked with a star or "(correct)" - or, from Word, made
        bold, underlined or highlighted. The mark comes off the option's text.
        More than one marked can't be told apart, so none is taken.
        """
        options: Dict[str, str] = {}
        marked: List[str] = []
        for letter, text in pairs:
            letter = letter.upper()
            text = text.strip()
            cleaned = re.sub(r'\s{2,}', ' ', ANSWER_MARK_RE.sub(' ', text)).strip()
            if cleaned != text:
                marked.append(letter)
            options[f'option{letter}'] = cleaned

        if len(marked) > 1:
            self.warnings.append(
                f"More than one option is marked as the answer to: {stem[:50]} - "
                "please choose the correct one."
            )
            return options, None
        return options, (marked[0] if marked else None)

    @staticmethod
    def _fold_answer_lines(lines: List[str]) -> List[str]:
        """
        Turn an "Answer: B" line under a question's options into a star on
        option B, the mark the question readers already look for. Left as it
        was, the line would be read as the start of the next question.
        """
        out: List[str] = []
        for line in lines:
            m = ANSWER_LINE_RE.match(line.strip())
            if m:
                letter = m.group(1).upper()
                placed = False
                for j in range(len(out) - 1, -1, -1):
                    option = OPTION_LINE_RE.match(out[j].strip())
                    if not option:
                        break  # past this question's options
                    if option.group(1).upper() == letter:
                        out[j] = out[j].rstrip() + ' *'
                        placed = True
                        break
                if placed:
                    continue
            out.append(line)
        return out

    def _parse_objective_question(self, content: str) -> Optional[Dict[str, Any]]:
        """Parse objective/multiple choice question"""
        if not content or not content.strip():
            return None

        # Extract question text (before options)
        option_pattern = r'\n\s*[A-E][\.\)]\s+'
        parts = re.split(option_pattern, content, maxsplit=1)

        question_text = parts[0].strip()

        # Validate we have question text
        if not question_text:
            self.warnings.append("Found objective question with no question text")
            return None

        # Extract options
        options_text = content[len(question_text):]
        option_matches = re.findall(
            r'\n\s*([A-E])[\.\)]\s+(.+?)(?=\n\s*[A-E][\.\)]|\n\n|$)',
            options_text,
            re.DOTALL
        )

        # Validate we have at least 2 options
        if len(option_matches) < 2:
            self.warnings.append(f"Objective question has fewer than 2 options: {question_text[:50]}...")
            # Still return it but warn the user

        options, correct_answer = self._options_and_answer(option_matches, question_text)

        return {
            'question': self._clean_html(question_text),
            'type': 'objective',
            'options': options,
            'correctAnswer': correct_answer,
            'marks': self._extract_marks(content)
        }

    def _parse_theory_question(self, content: str) -> Optional[Dict[str, Any]]:
        """Parse theory/essay question"""
        if not content or not content.strip():
            return None

        # Check for sub-questions (a, b, c, etc.)
        sub_question_pattern = r'\n\s*([a-z]|[ivxIVX]+)[\.\)]\s+'
        sub_parts = re.split(sub_question_pattern, content)

        if len(sub_parts) > 2:
            # Has sub-questions
            main_question = sub_parts[0].strip()
            sub_questions = []

            for i in range(1, len(sub_parts), 2):
                if i + 1 >= len(sub_parts):
                    break
                sub_text = sub_parts[i + 1].strip()
                if sub_text:  # Only add non-empty sub-questions
                    sub_questions.append({
                        'question': self._clean_html(sub_text),
                        'marks': self._extract_marks(sub_text)
                    })

            # Validate we have both main question and sub-questions
            if not main_question and not sub_questions:
                self.warnings.append("Found theory question with no content")
                return None

            return {
                'question': self._clean_html(main_question) if main_question else '<p>See sub-questions</p>',
                'type': 'theory',
                'marks': self._extract_marks(content),
                'subQuestions': sub_questions
            }
        else:
            # Simple theory question
            return {
                'question': self._clean_html(content),
                'type': 'theory',
                'marks': self._extract_marks(content)
            }

    def _parse_practical_question(self, content: str) -> Optional[Dict[str, Any]]:
        """Parse practical question"""
        if not content or not content.strip():
            return None

        return {
            'question': self._clean_html(content),
            'type': 'practical',
            'marks': self._extract_marks(content)
        }

    def _parse_generic_question(self, content: str) -> Optional[Dict[str, Any]]:
        """Parse generic question"""
        if not content or not content.strip():
            return None

        return {
            'question': self._clean_html(content),
            'type': 'custom',
            'marks': self._extract_marks(content)
        }

    def _extract_marks(self, text: str) -> int:
        """Extract marks from question text"""
        if not text:
            return 1  # Default for empty text

        # Look for patterns like (5 marks), [3], (10m), etc.
        patterns = [
            r'\((\d+)\s*marks?\)',
            r'\[(\d+)\s*marks?\]',
            r'\((\d+)m\)',
            r'\[(\d+)m\]'
        ]

        for pattern in patterns:
            try:
                match = re.search(pattern, text, re.IGNORECASE)
                if match:
                    marks = int(match.group(1))
                    # Validate reasonable marks range (1-100)
                    if 1 <= marks <= 100:
                        return marks
                    else:
                        self.warnings.append(f"Unusual mark value found: {marks}. Using default of 1.")
                        return 1
            except (ValueError, IndexError):
                continue

        return 1  # Default

    def _calculate_total_marks(self, sections: List[Dict[str, Any]]) -> int:
        """Calculate total marks from all sections"""
        total = 0
        for section in sections:
            for question in section['questions']:
                total += question.get('marks', 1)
                # Add sub-question marks
                for sub_q in question.get('subQuestions', []):
                    total += sub_q.get('marks', 1)
        return total

    def _determine_confidence(self, sections: List[Dict[str, Any]]) -> str:
        """Determine parsing confidence level"""
        if not sections:
            return 'low'

        # Check if we found structured questions
        total_questions = sum(len(s['questions']) for s in sections)

        if total_questions == 0:
            return 'low'
        elif total_questions < 5:
            return 'medium'
        else:
            # Check if we found section types correctly
            identified_sections = sum(1 for s in sections if s['type'] != 'custom')
            if identified_sections >= 2:
                return 'high'
            else:
                return 'medium'

    def _clean_html(self, text: str) -> str:
        """Clean and convert text to HTML"""
        if not text:
            return '<p></p>'

        # Preserve line breaks
        text = text.strip()

        # Basic HTML escaping for safety (prevent script injection)
        text = text.replace('&', '&amp;')
        text = text.replace('<', '&lt;')
        text = text.replace('>', '&gt;')

        # Convert newlines to <br> for display (now safe since < and > are escaped)
        text = text.replace('\n', '<br>')

        # Wrap in paragraph
        return f'<p>{text}</p>'

    def _convert_table_to_html(self, table: List[List[str]]) -> str:
        """Convert extracted table to HTML"""
        if not table or len(table) == 0:
            return ""

        try:
            html = '<table style="border-collapse: collapse; width: 100%; margin: 10px 0; border: 1px solid #ddd;">'

            # First row as header
            html += '<thead><tr>'
            for cell in table[0]:
                # Escape cell content for safety
                safe_cell = str(cell or "").replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                html += f'<th style="border: 1px solid #ddd; padding: 8px; background-color: #f0f0f0;">{safe_cell}</th>'
            html += '</tr></thead>'

            # Remaining rows as body
            html += '<tbody>'
            for row in table[1:]:
                if row:  # Skip empty rows
                    html += '<tr>'
                    for cell in row:
                        # Escape cell content for safety
                        safe_cell = str(cell or "").replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                        html += f'<td style="border: 1px solid #ddd; padding: 8px;">{safe_cell}</td>'
                    html += '</tr>'
            html += '</tbody></table>'

            return html
        except Exception as e:
            self.warnings.append(f"Error converting table to HTML: {str(e)}")
            return ""

    def _word_table_to_html(self, table: 'Table') -> str:
        """Convert Word table to HTML"""
        if not table or not table.rows or len(table.rows) == 0:
            return ""

        try:
            html = '<table style="border-collapse: collapse; width: 100%; margin: 10px 0; border: 1px solid #ddd;">'

            for i, row in enumerate(table.rows):
                html += '<tr>'
                for cell in row.cells:
                    tag = 'th' if i == 0 else 'td'
                    style = 'border: 1px solid #ddd; padding: 8px;'
                    if i == 0:
                        style += ' background-color: #f0f0f0;'
                    # Escape cell content for safety
                    safe_cell = str(cell.text or "").replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
                    html += f'<{tag} style="{style}">{safe_cell}</{tag}>'
                html += '</tr>'

            html += '</table>'
            return html
        except Exception as e:
            self.warnings.append(f"Error converting Word table to HTML: {str(e)}")
            return ""

    def _paragraph_to_html(self, para: 'Paragraph') -> str:
        """Convert Word paragraph to HTML with formatting"""
        try:
            # Simple conversion - can be enhanced to preserve bold, italic, etc.
            text = para.text.strip()
            if not text:
                return ""

            # Escape text content for safety
            safe_text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

            # Check for heading styles
            if para.style and para.style.name and para.style.name.startswith('Heading'):
                level = para.style.name[-1] if para.style.name[-1].isdigit() else '3'
                # Validate level is between 1-6
                if level.isdigit() and 1 <= int(level) <= 6:
                    return f'<h{level}>{safe_text}</h{level}>'

            return f'<p>{safe_text}</p>'
        except Exception as e:
            self.warnings.append(f"Error converting paragraph to HTML: {str(e)}")
            return ""
